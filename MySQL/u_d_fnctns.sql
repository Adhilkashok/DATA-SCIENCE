-- ?:SUM OF 2 NUMBERS
DELIMITER $$
CREATE FUNCTION ADD_NUMS(A INT,B INT)
RETURNS INT
DETERMINISTIC
BEGIN
RETURN A+B;
END $$
DELIMITER ;
SELECT ADD_NUMS(10,20) AS "SUMS";

