DELIMITER $$
CREATE FUNCTION TEN_PERCENT(SALARY DECIMAL(10,2))
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
RETURN (SALARY*10)/100;
END $$
DELIMITER ;
SELECT TEN_PERCENT(SALARY)AS "TEN PERCENT" FROM EMPLOYEE;









